"""Build the Phase 8 comparison tables and report figures from saved metrics."""

from __future__ import annotations

import argparse
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import pandas as pd


MODEL_LABELS = {
    "swin3d_t_paired_views": "Swin3D-T paired views",
    "x3d_s_late_fusion": "X3D-S late fusion",
    "x3d_m_late_fusion": "X3D-M late fusion",
}
DATASET_LABELS = {
    "rwf2000": "RWF-2000 test",
    "rlvs": "RLVS",
    "hockeyfights": "Hockey Fights",
}


def _markdown_table(frame: pd.DataFrame, path: Path, columns: list[str]) -> None:
    output = frame[columns].copy()
    for column in output.select_dtypes(include="number"):
        output[column] = output[column].map(
            lambda value: "" if pd.isna(value) else f"{value:.4f}"
        )
    headers = list(output.columns)
    lines = [
        "| " + " | ".join(headers) + " |",
        "| " + " | ".join("---" for _ in headers) + " |",
    ]
    lines.extend(
        "| " + " | ".join(str(value) for value in row) + " |"
        for row in output.itertuples(index=False, name=None)
    )
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def build(phase6_csv: Path, phase7_csv: Path, output_dir: Path) -> None:
    phase6 = pd.read_csv(phase6_csv)
    phase7 = pd.read_csv(phase7_csv)
    output_dir.mkdir(parents=True, exist_ok=True)

    phase6["model_name"] = phase6["model"].map(MODEL_LABELS).fillna(phase6["model"])
    phase6 = phase6.sort_values("f1_violent", ascending=False)
    phase6.to_csv(output_dir / "rwf2000_model_comparison.csv", index=False)
    _markdown_table(
        phase6,
        output_dir / "rwf2000_model_comparison.md",
        [
            "model_name",
            "accuracy",
            "precision_violent",
            "recall_violent",
            "f1_violent",
            "roc_auc",
            "clips_per_second",
            "milliseconds_per_clip",
        ],
    )

    phase7["model_name"] = phase7["model"].map(MODEL_LABELS).fillna(phase7["model"])
    phase7["dataset_name"] = phase7["dataset"].map(DATASET_LABELS).fillna(
        phase7["dataset"]
    )
    phase7 = phase7.loc[phase7["dataset"].isin(DATASET_LABELS)].copy()
    phase7.to_csv(output_dir / "cross_dataset_metrics.csv", index=False)
    _markdown_table(
        phase7,
        output_dir / "cross_dataset_metrics.md",
        [
            "model_name",
            "dataset_name",
            "clips",
            "accuracy",
            "precision_violent",
            "recall_violent",
            "f1_violent",
            "roc_auc",
            "false_positives",
            "false_negatives",
            "false_alarm_rate_nonviolent",
        ],
    )

    plot_data = phase7.pivot(index="model_name", columns="dataset_name", values="f1_violent")
    plot_data = plot_data.reindex(columns=[DATASET_LABELS[name] for name in DATASET_LABELS])
    axis = plot_data.plot(kind="bar", figsize=(10, 5.5), ylim=(0, 1), rot=0)
    axis.set_ylabel("Violent-class F1")
    axis.set_xlabel("")
    axis.set_title("Cross-dataset violent-class F1 at RWF validation thresholds")
    axis.legend(
        title="Evaluation set",
        loc="upper center",
        bbox_to_anchor=(0.5, -0.12),
        ncol=3,
        frameon=False,
    )
    axis.grid(axis="y", alpha=0.25)
    axis.set_axisbelow(True)
    plt.tight_layout(rect=(0, 0.06, 1, 1))
    plt.savefig(output_dir / "cross_dataset_f1.png", dpi=200)
    plt.close()

    fig, axis = plt.subplots(figsize=(8, 5.5))
    for _, row in phase6.iterrows():
        axis.scatter(row["milliseconds_per_clip"], row["f1_violent"], s=80)
        offset = (-8, 8) if row["milliseconds_per_clip"] > 60 else (6, 6)
        alignment = "right" if row["milliseconds_per_clip"] > 60 else "left"
        axis.annotate(
            row["model_name"],
            (row["milliseconds_per_clip"], row["f1_violent"]),
            xytext=offset,
            textcoords="offset points",
            ha=alignment,
            fontsize=8,
        )
    axis.set_xlabel("Milliseconds per clip (lower is faster)")
    axis.set_ylabel("Violent-class F1")
    axis.set_title("RWF-2000 test violent-class F1 versus inference latency")
    axis.grid(alpha=0.25)
    plt.tight_layout()
    plt.savefig(output_dir / "rwf2000_f1_vs_latency.png", dpi=200)
    plt.close()

    summary = """# Phase 8 results artifacts

Generated by `scripts/build_phase8_results.py` from the saved Phase 6 RWF test
comparison and Phase 7 cross-dataset metrics. Thresholds for cross-dataset rows
were selected using only RWF-2000 validation. Inference latency is the measured
single-GPU batch-size-1 result recorded in the Phase 6 comparison.

- `rwf2000_model_comparison.csv` and `.md`: held-out RWF-2000 test comparison.
- `cross_dataset_metrics.csv` and `.md`: RWF-2000 test, RLVS, and Hockey Fights.
- `cross_dataset_f1.png`: violent-class F1 across the three evaluation sets.
- `rwf2000_f1_vs_latency.png`: Phase 6 RWF test F1 versus measured latency.
- `local_environment_manifest.json`: versions and hashes from the packaging
  workspace; the Phase 7 runner writes the Kaggle run manifest separately.

The RWF test set participated in model comparison, so it is a model-selection
result rather than an untouched final test after Phase 6. External evaluations
are reported separately and were not used for threshold selection.
"""
    (output_dir / "README.md").write_text(summary, encoding="utf-8")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--phase6-csv",
        type=Path,
        default=Path("experiments/phase6/comparison/model_comparison.csv"),
    )
    parser.add_argument(
        "--phase7-csv",
        type=Path,
        default=Path("experiments/phase7/error_analysis/cross_dataset_metrics.csv"),
    )
    parser.add_argument("--output-dir", type=Path, default=Path("experiments/phase8"))
    args = parser.parse_args()
    build(args.phase6_csv, args.phase7_csv, args.output_dir)
    print(f"Wrote Phase 8 tables and plots to {args.output_dir}")


if __name__ == "__main__":
    main()
